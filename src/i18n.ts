/** Path for a page in a given language. `path` is the English path, e.g. "/apps/fidele". */
export function localePath(lang: Lang, path: string): string {
  const clean = path === '/' ? '' : path.replace(/\/$/, '');
  return lang === 'fr' ? `/fr${clean}` || '/fr' : clean || '/';
}

